"use client";

import { FormEvent, useEffect, useRef, useState } from "react";
import type { ChatMessage } from "@/lib/ai/gemini";
import type { QuickPrompt } from "@/lib/ai/quickInsights";
import { ChatCharts, type ChartSpec } from "@/components/ai/ChatCharts";

export type ChatAgent = "athena" | "oracle";

interface ChatbotWidgetProps {
  agent?: ChatAgent;
  /** Full live context (city snapshot + history) supplied by the dashboard. */
  getContext: () => string;
  /** Suggested questions answered instantly from live data, with charts (no model call). */
  quickPrompts?: QuickPrompt[];
}

interface DisplayMessage extends ChatMessage {
  id: number;
  /** Computed locally from live data rather than generated by Gemini. */
  instant?: boolean;
  charts?: ChartSpec[];
}

const THEME = {
  athena: {
    name: "Athena",
    subtitle: "Ithaca AI Assistant",
    header: "#6b0f1a",
    accent: "#6b0f1a",
    greeting: "Hello, Operator. I'm Athena, your Ithaca operations assistant. I can summarize the live asset list, trace an incident, or help you choose a safe recovery order.",
    placeholder: "Ask Athena a question…",
    thinking: "Athena is thinking…",
    tag: "Instant insight · computed from live data",
  },
  oracle: {
    name: "The Oracle",
    subtitle: "Ithaca Seer · Strategic foresight",
    header: "#35205f",
    accent: "#5b3d94",
    greeting: "Greetings, Operator. Ask what the omens foretell for Ithaca — cascading risks, fragile districts and the days ahead.",
    placeholder: "Ask the Oracle what lies ahead…",
    thinking: "The Oracle gazes into the smoke…",
    tag: "Instant foresight · modelled from live data and the simulated record",
  },
} as const;

function Avatar({ agent, size }: { agent: ChatAgent; size: "sm" | "lg" }) {
  if (agent === "athena") {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src="/art/helmet.png" alt="" aria-hidden className={`${size === "lg" ? "h-14" : "h-11"} w-auto shrink-0 drop-shadow-[0_3px_6px_rgba(0,0,0,.5)]`} />;
  }
  return (
    <span aria-hidden className={`${size === "lg" ? "h-14 w-14 text-3xl" : "h-11 w-11 text-2xl"} grid shrink-0 place-items-center rounded-full border border-[#c9a24b]/60 font-heading text-[#f0dcff] shadow-[0_3px_10px_rgba(0,0,0,.5)]`} style={{ background: "radial-gradient(circle at 50% 38%, #8d6ad0, #2a1650 72%)" }}>Ω</span>
  );
}

export function ChatbotWidget({ agent = "athena", getContext, quickPrompts }: ChatbotWidgetProps) {
  const t = THEME[agent];
  const [input, setInput] = useState("");
  const [messages, setMessages] = useState<DisplayMessage[]>([]);
  const [sending, setSending] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const nextId = useRef(1);
  const scrollRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
  }, [messages, sending]);

  function askQuick(prompt: QuickPrompt) {
    if (sending) return;
    setError(null);
    const { text, charts } = prompt.answer();
    setMessages((current) => [
      ...current,
      { id: nextId.current++, role: "user", content: prompt.label },
      { id: nextId.current++, role: "assistant", content: text, charts, instant: true },
    ]);
  }

  async function sendMessage(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const content = input.trim();
    if (!content || sending) return;

    const userMessage: DisplayMessage = { id: nextId.current++, role: "user", content };
    const conversation = [...messages, userMessage].slice(-20);
    setMessages(conversation);
    setInput("");
    setError(null);
    setSending(true);

    try {
      const response = await fetch("/api/chatbot", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          agent,
          messages: conversation.map(({ role, content: messageContent }) => ({ role, content: messageContent })),
          context: getContext(),
        }),
      });
      if (!response.ok || !response.body) {
        const result = await response.json().catch(() => ({}));
        throw new Error(result.error ?? "The assistant is unavailable.");
      }
      // Words appear as Gemini writes them (streamed), so the first text shows almost instantly.
      const reader = response.body.getReader();
      const decoder = new TextDecoder();
      const replyId = nextId.current++;
      let reply = "";
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        reply += decoder.decode(value, { stream: true });
        const snapshot = reply;
        setMessages((current) => current.some((m) => m.id === replyId)
          ? current.map((m) => (m.id === replyId ? { ...m, content: snapshot } : m))
          : [...current, { id: replyId, role: "assistant", content: snapshot }]);
        setSending(false);
      }
      if (!reply.trim()) throw new Error("The assistant returned an empty answer.");
    } catch (sendError) {
      setError(sendError instanceof Error ? sendError.message : "The assistant is unavailable.");
    } finally {
      setSending(false);
    }
  }

  const bubble = "relative mb-2 rounded-2xl rounded-bl-sm border border-[#b98a4a]/60 bg-[#fff4d6]/90 p-4 font-heading text-base font-normal leading-7 text-black";
  const tail = <span aria-hidden className="absolute -left-2 bottom-3 h-4 w-4 rotate-45 border-b border-l border-[#b98a4a]/60 bg-[#fff4d6]" />;

  return (
    <section
      aria-label={`${t.name} chat`}
      className="[text-shadow:none] flex h-full min-h-[480px] w-full flex-col overflow-hidden rounded-2xl border border-[#6b4220] bg-[#7a5230] bg-[url(/art/parchment.jpg)] bg-cover bg-center shadow-[0_18px_50px_rgba(0,0,0,.5)]"
    >
      <header className="flex items-center gap-3 px-4 py-3.5 text-[#f6e6c4]" style={{ background: t.header }}>
        <Avatar agent={agent} size="sm" />
        <div className="min-w-0 flex-1">
          <h2 className="font-heading text-lg font-normal tracking-[.14em]">{t.name}</h2>
          <p className="mt-0.5 text-[10px] text-[#f6e6c4]/60">{t.subtitle}</p>
        </div>
      </header>

      <div ref={scrollRef} className="flex-1 space-y-3 overflow-y-auto p-5 sm:px-10">
        <div className="flex items-end gap-3">
          <Avatar agent={agent} size="lg" />
          <div className={bubble}>{tail}<p>{t.greeting}</p></div>
        </div>

        {quickPrompts && quickPrompts.length > 0 && messages.length === 0 && (
          <div className="pl-[4.25rem]">
            <p className="mb-2 text-[11px] font-semibold uppercase tracking-[.2em] text-[#4a2c14]">Suggested questions</p>
            <div className="grid gap-2 sm:grid-cols-2">
              {quickPrompts.map((p) => (
                <button key={p.label} type="button" onClick={() => askQuick(p)} className="rounded-xl border border-[#b98a4a]/60 bg-[#fff4d6]/85 px-4 py-3 text-left font-heading text-[15px] leading-snug text-black transition hover:-translate-y-0.5 hover:bg-[#fff9e8]" style={{ ["--hover" as string]: t.accent }} onMouseEnter={(e) => (e.currentTarget.style.borderColor = t.accent)} onMouseLeave={(e) => (e.currentTarget.style.borderColor = "")}>
                  {p.label}<span aria-hidden className="ml-1.5" style={{ color: t.accent }}>→</span>
                </button>
              ))}
            </div>
          </div>
        )}

        {messages.map((message) => message.role === "user" ? (
          <div key={message.id} className="ml-auto max-w-[80%] whitespace-pre-wrap rounded-2xl rounded-br-sm border border-[#b98a4a]/60 bg-[#fff4d6]/90 p-4 font-heading text-base font-normal leading-7 text-black">
            {message.content}
          </div>
        ) : (
          <div key={message.id} className="flex items-end gap-3">
            <Avatar agent={agent} size="lg" />
            <div className={`${bubble} ${message.charts ? "w-full max-w-[min(100%,720px)]" : "max-w-[80%]"} whitespace-pre-wrap`}>
              {tail}
              {message.content}
              {message.charts && <ChatCharts charts={message.charts} />}
              {message.instant && <p className="mt-3 border-t border-[#b98a4a]/40 pt-2 font-sans text-[10px] uppercase tracking-[.16em] text-[#6b4a22]">{t.tag}</p>}
            </div>
          </div>
        ))}

        {sending && (
          <div role="status" className="flex items-end gap-3">
            <Avatar agent={agent} size="lg" />
            <p className="mb-2 rounded-2xl rounded-bl-sm border border-[#b98a4a]/60 bg-[#fff4d6]/90 px-4 py-3 font-heading text-base italic text-black">{t.thinking}</p>
          </div>
        )}
        {error && (
          <div role="alert" className="flex items-end gap-3">
            <Avatar agent={agent} size="lg" />
            <div className="relative mb-2 max-w-[80%] rounded-2xl rounded-bl-sm border border-[#6b0f1a]/50 bg-[#fff4d6]/90 p-4 font-heading text-base leading-7 text-[#6b0f1a]">
              <span aria-hidden className="absolute -left-2 bottom-3 h-4 w-4 rotate-45 border-b border-l border-[#6b0f1a]/50 bg-[#fff4d6]" />
              Busy right now—processing your request shortly...
            </div>
          </div>
        )}
      </div>

      <form onSubmit={sendMessage} className="border-t border-[#6b4220]/60 bg-[#2a150d]/80 p-3 backdrop-blur-sm">
        {quickPrompts && quickPrompts.length > 0 && messages.length > 0 && (
          <div className="mb-2.5 flex gap-2 overflow-x-auto pb-1" aria-label="Suggested questions">
            {quickPrompts.map((p) => (
              <button key={p.label} type="button" onClick={() => askQuick(p)} className="shrink-0 rounded-full border border-[#b98a4a]/60 bg-[#fff4d6]/90 px-3.5 py-1.5 font-heading text-[13px] text-black transition hover:bg-white">{p.label}</button>
            ))}
          </div>
        )}
        <div className="flex items-end gap-2 rounded-xl border border-[#b98a4a]/60 bg-[#f6e6c4] p-2 focus-within:border-[#e4aa56]">
          <textarea
            value={input}
            onChange={(event) => setInput(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === "Enter" && !event.shiftKey) {
                event.preventDefault();
                event.currentTarget.form?.requestSubmit();
              }
            }}
            aria-label={`Message ${t.name}`}
            placeholder={t.placeholder}
            rows={1}
            maxLength={2000}
            className="max-h-32 min-h-11 flex-1 resize-y bg-transparent px-1 py-2.5 text-base text-[#3b2412] outline-none placeholder:text-[#8a6d4a]"
          />
          <button
            type="submit"
            disabled={!input.trim() || sending}
            aria-label="Send message"
            className="grid h-9 w-9 shrink-0 place-items-center rounded-lg text-sm font-bold text-[#f6e6c4] transition hover:brightness-110 disabled:cursor-not-allowed disabled:opacity-40"
            style={{ background: t.header }}
          >
            ↑
          </button>
        </div>
        <p className="mt-2 text-center text-[9px] text-[#f6e6c4]/50">AI responses can be inaccurate. Verify critical decisions.</p>
      </form>
    </section>
  );
}
